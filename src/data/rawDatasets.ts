// GER Subcategory definitions based on course code prefixes and authentic SAS offerings
export function getGERSubCategory(courseCode: string): GERSubCategory | null {
  const prefix = courseCode.replace(/[0-9].*$/, '').toUpperCase();

  // 1. Humanities and Languages
  if (['HST', 'LIT', 'PHI', 'PHL', 'SAN', 'PER', 'GER', 'URD', 'HIN', 'FRE', 'JAP', 'MAN', 'SPA'].includes(prefix) || courseCode === 'COM114' || courseCode === 'SAS101') {
    return 'Humanities and Languages';
  }

  // 2. Social Sciences
  if (['ECO', 'SPS', 'PSY', 'SOC'].includes(prefix)) {
    return 'Social Sciences';
  }

  // 3. Mathematical and Physical Sciences
  if (['MAT', 'PHY', 'STA', 'CSC', 'CSE', 'EEE'].includes(prefix)) {
    return 'Mathematical and Physical Sciences';
  }

  // 4. Biological and Life Sciences
  if (['BIO', 'ENV', 'CHE'].includes(prefix)) {
    return 'Biological and Life Sciences';
  }

  // 5. Performing and Visual Arts
  if (['PVA', 'MUS', 'DES'].includes(prefix)) {
    return 'Performing and Visual Arts';
  }

  return null;
}
